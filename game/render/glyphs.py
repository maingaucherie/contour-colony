def _ellipse(cx, cy, rx, ry, n=10, start=0.0, end=2 * math.pi):
    pts = [(cx + rx * math.cos(start + (end - start) * k / n), cy + ry * math.sin(start + (end - start) * k / n))
           for k in range(n + 1)]
    return pts


def _box(x0, y0, x1, y1):
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1), (x0, y0)]


